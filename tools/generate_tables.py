"""Regenerate small embedded tables using the experiment's pinned pycrate.

Run from repository root in the satellite Python environment. Outputs contain
only root SIB5/SIB8 schema metadata, QPP coefficients and the saved IERS table.
No recorded timestamp or payload is compiled into the production decoder.
"""
from datetime import datetime, timezone
from pathlib import Path
import re
import sys
from pycrate_asn1dir import RRCLTE

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tests/reference'))
from vendor.estevez_lte import f1f2_table


def generate():
    nodes, edges = [], []
    kinds = {'SEQUENCE': 0, 'CHOICE': 1, 'SEQUENCE OF': 2,
             'INTEGER': 3, 'ENUMERATED': 4, 'BOOLEAN': 5, 'BIT STRING': 6}

    def visit(obj, name=''):
        typ = obj.TYPE
        kind = kinds[typ]
        index = len(nodes)
        nodes.append(None)
        children, lo, hi = [], 0, 0
        if typ in ('SEQUENCE', 'CHOICE'):
            children = [visit(obj._cont[n], n) for n in obj._root]
        elif typ == 'SEQUENCE OF':
            children = [visit(obj._cont)]
            lo, hi = obj._const_sz.lb, obj._const_sz.ub
            assert obj._const_sz.ext is None
        elif typ == 'INTEGER':
            lo, hi = obj._const_val.lb, obj._const_val.ub
            assert obj._const_val.ext is None
        elif typ == 'ENUMERATED':
            hi = len(obj._root) - 1
        elif typ == 'BIT STRING':
            lo, hi = obj._const_sz.lb, obj._const_sz.ub
            assert obj._const_sz.ext is None
        tag = {'cdma-EUTRA-Synchronisation': 1,
               'synchronousSystemTime': 2, 'asynchronousSystemTime': 3}.get(name, 0)
        first = len(edges)
        edges.extend(children)
        nodes[index] = (kind, int(getattr(obj, '_ext', None) is not None),
                        int(obj._opt or obj._def is not None), tag,
                        first, len(children), lo, hi)
        return index

    sib5 = visit(RRCLTE.EUTRA_RRC_Definitions.SystemInformationBlockType5)
    sib8 = visit(RRCLTE.EUTRA_RRC_Definitions.SystemInformationBlockType8)
    qpp = [(k, *f1f2_table(k)) for k in range(40, 513, 8)]
    leap_text = (ROOT / 'extras/iers-leap-seconds.dat').read_text()
    expires = datetime.strptime(re.search(r'expires on (\d+ \w+ \d+)', leap_text)[1],
                                '%d %B %Y').replace(tzinfo=timezone.utc)
    leaps = []
    for line in leap_text.splitlines():
        f = line.split()
        if len(f) == 5 and not line.lstrip().startswith('#'):
            _, day, month, year, tai = f
            epoch = int(datetime(int(year), int(month), int(day), tzinfo=timezone.utc).timestamp())
            leaps.append((epoch, int(tai) - 19))
    out = ['// SPDX-License-Identifier: GPL-3.0-only',
           '// Generated by experiments/onboard-lte/generate_tables.py; do not edit.',
           '// ASN.1 metadata: TS 36.331, via pycrate 0.8.1. QPP: TS 36.212.',
           'static const SchemaNode schema[] = {']
    out += ['  {' + ','.join(map(str, n)) + '},' for n in nodes]
    out += ['};', 'static const uint16_t children[] = {' + ','.join(map(str, edges)) + '};',
            f'static constexpr unsigned Sib5Node = {sib5}, Sib8Node = {sib8};',
            'static const uint16_t qpp[][3] = {']
    out += ['  {' + ','.join(map(str, q)) + '},' for q in qpp]
    out += ['};', 'struct LeapEntry { int64_t utc; int8_t offset; };',
            'static const LeapEntry leaps[] = {']
    out += [f'  {{{utc}LL,{offset}}},' for utc, offset in leaps]
    out += ['};', f'static constexpr int64_t LeapExpiry = {int(expires.timestamp())}LL;', '']
    target = ROOT / 'src/LteTimeTables.inc'
    target.write_text('\n'.join(out), encoding='utf-8')
    print(f'{target.name}: {len(nodes)} schema nodes, {len(qpp)} QPP entries, {len(leaps)} leap entries')


if __name__ == '__main__':
    generate()
