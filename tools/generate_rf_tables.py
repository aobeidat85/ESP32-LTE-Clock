"""The same default Kaiser polyphase FIR as scipy.signal.resample_poly."""
from pathlib import Path
from scipy.signal import firwin

dest = Path(__file__).resolve().parents[1] / 'src/LteRfFir.inc'
h = firwin(501, 1/25, window=('kaiser', 5.0))
text = ['// Generated by experiments/onboard-lte/generate_rf_tables.py.',
        '// scipy resample_poly default: half_len=250, cutoff=1/25, Kaiser beta=5.',
        'static const float Fir[] = {']
text += [','.join(f'{x:.10e}f' for x in h[i:i+8]) + ',' for i in range(0, len(h), 8)]
text += ['};', '']
dest.write_text('\n'.join(text))
print(dest.name)
